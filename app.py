@app.route('/api/status', methods=['GET'])
def api_status():
    """API: Check status of all servers."""
    manager = get_dns_manager()
    status = {}

    for name, config in manager.servers.items():
        is_online = manager.check_status(config['ip'])
        status[name] = {
            'ip': config['ip'],
            'online': is_online
        }

    return jsonify(status)

